namespace CaseCompat.Core.Repair;

/*
 * Generic spelling-only representation of one existing aggregate physical
 * regular-file leaf.
 *
 * WindowsLogicalPath identifies the Windows-logical leaf.
 *
 * PhysicalRelativePaths contains the exact Data-relative physical spellings
 * observed for that leaf. Component casing is evidence and must therefore be
 * retained exactly.
 *
 * This type deliberately contains no physical-content classification,
 * snapshots, inode-generation evidence, provider/source selection, persistence
 * schema, or repair authority.
 */
public sealed record DataRelativePathAggregatePhysicalSpellingLeaf(
    string WindowsLogicalPath,
    IReadOnlyList<string> PhysicalRelativePaths
);

/*
 * Pure physical-leaf-left join between:
 *
 * - an existing aggregate physical-spelling leaf universe; and
 * - generic C4D-1 consumer-spelling evidence.
 *
 * Every physical leaf produces exactly one C4D-2 spelling relation.
 *
 * A physical leaf with no matching consumer record receives canonical
 * NoConsumerEvidence generated by C4D-1.
 *
 * Consumer evidence whose Windows-logical path has no physical leaf is outside
 * this projector's output universe. This is expected for consumers with no
 * loose physical representation, including consumers that may be archive-only.
 * Such consumer records are still fully validated before projection; malformed
 * or noncanonical consumer evidence is never silently ignored.
 *
 * Physical/content state is intentionally absent. UniqueRepresentation,
 * EquivalentContentMultipleRepresentations, and
 * ConflictingContentMultipleRepresentations remain an independent dimension.
 *
 * No filesystem access, manifest persistence, provider precedence, content
 * hashing, source selection, repair planning, authorization, execution,
 * rollback, or recovery occurs here.
 */
public static class
    DataRelativePathAggregateConsumerPhysicalSpellingProjector
{
    public static
        IReadOnlyList<DataRelativePathAggregateConsumerPhysicalSpellingEvidence>
        Project(
            IReadOnlyList<DataRelativePathAggregatePhysicalSpellingLeaf>
                physicalLeaves,
            IReadOnlyList<DataRelativePathAggregateConsumerSpellingEvidence>
                consumerSpellings)
    {
        ArgumentNullException.ThrowIfNull(
            physicalLeaves
        );

        ArgumentNullException.ThrowIfNull(
            consumerSpellings
        );

        Dictionary<
            string,
            DataRelativePathAggregateConsumerSpellingEvidence
        > consumersByLogicalPath =
            ValidateAndIndexConsumerSpellings(
                consumerSpellings
            );

        var physicalLeavesByLogicalPath =
            new Dictionary<
                string,
                DataRelativePathAggregatePhysicalSpellingLeaf
            >(
                StringComparer.Ordinal
            );

        /*
         * Build canonical NoConsumerEvidence for every physical leaf first.
         *
         * Besides establishing the left-join default, C4D-1 validates that the
         * supplied Windows-logical key is canonical before it is used as a
         * dictionary identity.
         */
        var noConsumerEvidenceByLogicalPath =
            new Dictionary<
                string,
                DataRelativePathAggregateConsumerSpellingEvidence
            >(
                StringComparer.Ordinal
            );

        foreach (
            DataRelativePathAggregatePhysicalSpellingLeaf? physicalLeaf
            in physicalLeaves)
        {
            if (physicalLeaf is null)
            {
                throw new ArgumentException(
                    "The aggregate physical-spelling leaf collection " +
                    "contains a null leaf.",
                    nameof(physicalLeaves)
                );
            }

            if (physicalLeaf.PhysicalRelativePaths is null)
            {
                throw new ArgumentException(
                    $"Aggregate physical-spelling leaf " +
                    $"'{physicalLeaf.WindowsLogicalPath}' has no physical " +
                    "relative-path collection.",
                    nameof(physicalLeaves)
                );
            }

            DataRelativePathAggregateConsumerSpellingEvidence
                noConsumerEvidence =
                    DataRelativePathAggregateConsumerSpellingClassifier
                        .Classify(
                            physicalLeaf.WindowsLogicalPath,
                            Array.Empty<string>()
                        );

            if (!physicalLeavesByLogicalPath.TryAdd(
                    noConsumerEvidence.WindowsLogicalPath,
                    physicalLeaf))
            {
                throw new ArgumentException(
                    $"Aggregate physical-spelling logical leaf " +
                    $"'{noConsumerEvidence.WindowsLogicalPath}' occurs more " +
                    "than once.",
                    nameof(physicalLeaves)
                );
            }

            noConsumerEvidenceByLogicalPath.Add(
                noConsumerEvidence.WindowsLogicalPath,
                noConsumerEvidence
            );
        }

        var result =
            new List<
                DataRelativePathAggregateConsumerPhysicalSpellingEvidence
            >(
                physicalLeavesByLogicalPath.Count
            );

        foreach (
            KeyValuePair<
                string,
                DataRelativePathAggregatePhysicalSpellingLeaf
            > pair
            in physicalLeavesByLogicalPath.OrderBy(
                pair =>
                    pair.Key,
                StringComparer.Ordinal
            ))
        {
            string windowsLogicalPath =
                pair.Key;

            DataRelativePathAggregatePhysicalSpellingLeaf physicalLeaf =
                pair.Value;

            DataRelativePathAggregateConsumerSpellingEvidence
                consumerSpelling =
                    consumersByLogicalPath.TryGetValue(
                        windowsLogicalPath,
                        out DataRelativePathAggregateConsumerSpellingEvidence?
                            observedConsumer)
                        ? observedConsumer
                        : noConsumerEvidenceByLogicalPath[
                            windowsLogicalPath
                        ];

            /*
             * C4D-2 owns all spelling-relation validation and classification:
             *
             * - every physical path must be a valid Data-relative path;
             * - every physical path must map to this logical leaf;
             * - physical separator variants are normalized;
             * - physical exact spellings are ordinally deduplicated/sorted;
             * - consumer evidence is canonical-revalidated;
             * - exact-vs-case-mismatch state is determined.
             */
            result.Add(
                DataRelativePathAggregateConsumerPhysicalSpellingClassifier
                    .Classify(
                        consumerSpelling,
                        physicalLeaf.PhysicalRelativePaths
                    )
            );
        }

        return result.ToArray();
    }

    private static Dictionary<
        string,
        DataRelativePathAggregateConsumerSpellingEvidence
    > ValidateAndIndexConsumerSpellings(
        IReadOnlyList<DataRelativePathAggregateConsumerSpellingEvidence>
            consumerSpellings)
    {
        var consumersByLogicalPath =
            new Dictionary<
                string,
                DataRelativePathAggregateConsumerSpellingEvidence
            >(
                StringComparer.Ordinal
            );

        foreach (
            DataRelativePathAggregateConsumerSpellingEvidence? consumerSpelling
            in consumerSpellings)
        {
            if (consumerSpelling is null)
            {
                throw new ArgumentException(
                    "The aggregate consumer-spelling evidence collection " +
                    "contains a null entry.",
                    nameof(consumerSpellings)
                );
            }

            if (consumerSpelling.DistinctRequestedPaths is null)
            {
                throw new ArgumentException(
                    $"Consumer spelling evidence for " +
                    $"'{consumerSpelling.WindowsLogicalPath}' has no " +
                    "requested-path collection.",
                    nameof(consumerSpellings)
                );
            }

            /*
             * Public record instances can be manually constructed.
             * Re-run C4D-1 and require byte-for-byte canonical agreement before
             * allowing the record to participate in this join.
             */
            DataRelativePathAggregateConsumerSpellingEvidence canonical =
                DataRelativePathAggregateConsumerSpellingClassifier
                    .Classify(
                        consumerSpelling.WindowsLogicalPath,
                        consumerSpelling.DistinctRequestedPaths
                    );

            if (
                canonical.State != consumerSpelling.State ||
                !canonical.DistinctRequestedPaths.SequenceEqual(
                    consumerSpelling.DistinctRequestedPaths,
                    StringComparer.Ordinal
                ))
            {
                throw new ArgumentException(
                    $"Consumer spelling evidence for " +
                    $"'{consumerSpelling.WindowsLogicalPath}' is not in the " +
                    "canonical form produced by the aggregate consumer " +
                    "spelling classifier.",
                    nameof(consumerSpellings)
                );
            }

            if (!consumersByLogicalPath.TryAdd(
                    canonical.WindowsLogicalPath,
                    consumerSpelling))
            {
                throw new ArgumentException(
                    $"Consumer spelling evidence for Windows-logical leaf " +
                    $"'{canonical.WindowsLogicalPath}' occurs more than once.",
                    nameof(consumerSpellings)
                );
            }
        }

        return consumersByLogicalPath;
    }
}
